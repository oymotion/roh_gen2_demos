def checkRunLoop():
    global _runloop, _needCloseRunloop, _event_thread
    if _runloop == None or not _runloop.is_running():
        try:
            _runloop = asyncio.get_running_loop()
        except Exception as e:
            _needCloseRunloop = True
            _runloop = asyncio.new_event_loop()
            _event_thread = threading.Thread(target=start_loop, args=(_runloop,))
            _event_thread.daemon = True
            _event_thread.name = "SensorController event"
            _event_thread.start()
            time.sleep(0.1)


def Terminate():
    global _runloop, _needCloseRunloop, _event_thread, _terminated
    _terminated = True

    # 如果不是我们创建的 loop（例如用户自己的 qasync/Qt loop），不要动它
    if not _needCloseRunloop or _runloop is None:
        return

    def _cancel_tasks():
        try:
            # 在 loop 线程内部调用，有运行中的事件循环
            for task in asyncio.all_tasks():
                if not task.done():
                    task.cancel()
        except Exception:
            # 取消任务失败时不阻塞终止流程
            pass

    try:
        # 取消 / stop 都必须在 loop 所在线程执行，避免跨线程调用 asyncio API 抛异常
        if _runloop.is_running():
            _runloop.call_soon_threadsafe(_cancel_tasks)
            time.sleep(0.2)
            _runloop.call_soon_threadsafe(_runloop.stop)

        if _event_thread is not None and _event_thread.is_alive():
            _event_thread.join(timeout=3.0)

        # 不再主动 close loop：Windows 的 ProactorEventLoop 在 still-running 时 close()
        # 会抛 RuntimeError。守护线程会在 loop stop 后自然退出，进程退出时回收资源。
    except Exception as e:
        SdkLog.exception(_TAG, "Error during terminate")


def async_exec(function, runloop=None):
    checkRunLoop()
    if runloop == None:
        runloop = _runloop
    task: asyncio.Future = None
    try:
        task = asyncio.run_coroutine_threadsafe(function, runloop)
        running_tasks.add(task)
        task.add_done_callback(lambda t: running_tasks.remove(t))
    except Exception as e:
        SdkLog.e(_TAG, f"async_exec failed: {e}")


def sync_call(function, _timeout=_TIMEOUT, runloop=None) -> any:
    checkRunLoop()
    task: asyncio.Future = None
    if runloop == None:
        runloop = _runloop
    try:
        task = asyncio.run_coroutine_threadsafe(asyncio.wait_for(function, _timeout), runloop)
        running_tasks.add(task)
        task.add_done_callback(lambda t: running_tasks.remove(t))
        return task.result(timeout=_timeout)
    except Exception as e:
        SdkLog.e(_TAG, f"sync_call failed: {e}")


async def async_call(function, _timeout=_TIMEOUT, runloop=None) -> any:
    checkRunLoop()
    task: asyncio.Future = None
    if runloop == None:
        runloop = _runloop
    try:
        task = asyncio.run_coroutine_threadsafe(asyncio.wait_for(function, _timeout), runloop)
        running_tasks.add(task)
        task.add_done_callback(lambda t: running_tasks.remove(t))
    except Exception as e:
        SdkLog.e(_TAG, f"async_call failed: {e}")

    while not _terminated and not task.done():
        await asyncio.sleep(0.1)

    try:
        if not task.cancelled():
            return task.result()
    except Exception as e:
        SdkLog.e(_TAG, f"async_call result failed: {e}")
        return


def start_loop(loop: asyncio.BaseEventLoop):
    # asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    asyncio.set_event_loop(loop)
    loop.run_forever()


